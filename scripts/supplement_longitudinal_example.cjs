"use strict";
// One-off normal form entry for the explicitly approved four-record example.
// No product import/demo control is installed by this script.
const assert = require("node:assert/strict");
const PROJECTS = ["fvp_sj", "fvp_cmj", "sprint_fvp", "lactate", "cpet"];
async function enterSupplement(page, plan, options = {}) {
  assert.equal(plan.records.length, 4);
  assert.ok(plan.athleteId && plan.records.every(record => record.recordId && record.date));
  const readLibrary = () => page.evaluate(async () => JSON.stringify(await App.getRepository().exportLibrary())).then(JSON.parse);
  const before = await readLibrary();
  if (options.before) await options.before(before);
  await page.evaluate(async athleteId => { await App.selectAthlete(athleteId); }, plan.athleteId);
  const field = key => page.locator(`[data-path="${key}"]`);
  const set = async (key, value) => {
    const control = field(key);
    assert.equal(await control.count(), 1, "A unique normal input is required: " + key);
    for (const disclosure of await control.locator("xpath=ancestor::details[not(@open)]").all()) await disclosure.locator(":scope > summary").click();
    const kind = await control.evaluate(node => ({ tag: node.tagName, type: node.type }));
    if (kind.type === "checkbox") await control.setChecked(value);
    else if (kind.tag === "SELECT") await control.selectOption(String(value));
    else { await control.fill(String(value)); await control.press("Tab"); }
  };
  const enter = tab => page.evaluate(tab => App.entry(tab), tab);
  const receipt = { normalFormEntry: true, projects: PROJECTS, records: [], beforeCounts: { athletes: before.athletes.length, records: before.athletes.reduce((count, owner) => count + owner.records.length, 0) } };
  for (const record of plan.records) {
    const current = (await readLibrary()).athletes.find(owner => owner.id === plan.athleteId)?.records.find(item => item.recordId === record.recordId);
    assert.ok(current && current.athlete.date === record.date, "Existing sample record identity differs");
    for (const id of PROJECTS) assert.equal(current.enabled[id], false, "Supplement must not overwrite an enabled project: " + id);
    await page.evaluate(async recordId => { await App.selectRecord(recordId); App.openEntry("plan"); }, record.recordId);
    await page.waitForFunction(() => App.getUIState().mode === "entry");
    for (const id of PROJECTS) await field("enabled." + id).check();
    for (const id of PROJECTS) {
      const project = record.projects[id];
      assert.ok(project, "Missing approved project data: " + id);
      await enter(id);
      for (const [key, value] of Object.entries(project.parameters || {})) await set(key, value);
      if (id === "cpet") continue;
      const desired = project.rows || [];
      let count = await page.evaluate(id => App.getState().data[id].length, id);
      assert.ok(count <= desired.length, "Never remove existing trials during supplementation");
      while (count < desired.length) {
        await page.evaluate(({ id, shape }) => id === "sprint_fvp" ? App.addRow(id, -1, shape) : App.addRow(id), { id, shape: desired[count]?.splits?.length === 6 ? "six" : "four" });
        count++;
      }
      for (const [index, row] of desired.entries()) {
        if (id === "sprint_fvp") {
          let splitCount = await page.evaluate(index => App.getState().data.sprint_fvp[index].splits.length, index);
          assert.ok(splitCount <= row.splits.length, "Never remove existing sprint splits");
          while (splitCount++ < row.splits.length) await page.evaluate(index => App.addSprintSplit(index), index);
          for (const [splitIndex, split] of row.splits.entries()) for (const [key, value] of Object.entries(split)) {
            assert.notEqual(key, "id", "New split IDs are generated by normal entry");
            await set(`data.${id}.${index}.splits.${splitIndex}.${key}`, value);
          }
        }
        for (const [key, value] of Object.entries(row)) {
          if (key === "splits") continue;
          assert.notEqual(key, "id", "New trial IDs are generated by normal entry");
          await set(`data.${id}.${index}.${key}`, value);
        }
      }
    }
    await enter("review");
    await page.locator("#entryFinish").click();
    await page.waitForFunction(() => App.getUIState().mode === "report");
    assert.equal(await page.evaluate(() => App.saveNow()), true);
    const saved = (await readLibrary()).athletes.find(owner => owner.id === plan.athleteId).records.find(item => item.recordId === record.recordId);
    if (options.record) await options.record(saved, record);
    receipt.records.push({ recordId: saved.recordId, date: saved.athlete.date, saved: true });
  }
  await page.evaluate(async ids => { await App.selectRecords(ids); }, plan.records.map(record => record.recordId));
  await page.waitForFunction(() => App.getLongitudinal()?.periods.length === 4);
  assert.equal(await page.evaluate(() => App.saveNow()), true);
  const after = await readLibrary();
  if (options.after) await options.after(after, before);
  receipt.afterCounts = { athletes: after.athletes.length, records: after.athletes.reduce((count, owner) => count + owner.records.length, 0) };
  assert.deepEqual(receipt.afterCounts, receipt.beforeCounts, "Supplementing data must not add athletes or test records");
  return receipt;
}
module.exports = { enterSupplement, PROJECTS };
